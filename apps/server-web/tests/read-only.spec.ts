import { test, expect } from '@playwright/test';

test.use({ baseURL: 'http://127.0.0.1:18788' });

test('browse real synced content, inspect progress and rejection receipts', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/library/');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('用户名').fill('admin');
  await page.getByLabel('密码', { exact: true }).fill('memedock-test-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '图库', exact: true })).toBeVisible();
  const tile = page.getByRole('button', { name: '查看 云端猫猫', exact: true });
  await expect(tile).toBeVisible();
  await expect.poll(() => tile.locator('img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  await page.route('**/api/v1/admin/library/stickers?*', route => route.abort());
  await page.getByRole('button', { name: '刷新图库', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('网络连接失败');
  await expect(tile).toBeVisible();
  await page.unroute('**/api/v1/admin/library/stickers?*');
  await page.getByRole('button', { name: '重新加载', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/library-desktop.png', fullPage: true });
  await tile.click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('heading', { name: '表情详情' })).toBeVisible();
  await expect(dialog.getByText('聊天常用', { exact: true })).toBeVisible();
  await expect(dialog.getByText('开心', { exact: true })).toBeVisible();
  await expect.poll(() => dialog.locator('img').evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth === 512)).toBe(true);
  await page.screenshot({ path: 'test-results/library-detail.png', fullPage: true });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(tile).toBeFocused();
  await page.getByRole('combobox', { name: '标签' }).fill('开心');
  await page.getByRole('option', { name: '开心', exact: true }).click();
  await expect(tile).toBeVisible();
  await page.getByRole('button', { name: '清除标签', exact: true }).click();
  await page.getByRole('checkbox', { name: '星标' }).check();
  await expect(page.getByRole('heading', { name: '未找到匹配表情' })).toBeVisible();
  await page.getByRole('button', { name: '清除筛选', exact: true }).click();
  await page.getByRole('searchbox', { name: '搜索云端内容' }).fill('不存在的关键词');
  await page.getByRole('button', { name: '搜索', exact: true }).click();
  await expect(page.getByRole('heading', { name: '未找到匹配表情' })).toBeVisible();
  await page.getByRole('button', { name: '清除筛选', exact: true }).click();
  await expect(tile).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/library-mobile.png', fullPage: true });
  await tile.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/library-detail-mobile.png' });
  await page.getByRole('button', { name: '关闭详情' }).click();
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.getByRole('link', { name: '同步状态', exact: true }).click();
  await expect(page.getByRole('link', { name: '同步状态', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByText('已追平云端', { exact: true })).toBeVisible();
  await expect(page.getByRole('progressbar')).toBeVisible();
  await page.screenshot({ path: 'test-results/sync-desktop.png', fullPage: true });
  await page.getByRole('link', { name: '查看被拒绝的提交' }).click();
  await expect(page.getByRole('link', { name: '操作记录', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(page.getByLabel('筛选提交结果')).toHaveValue('rejected');
  await expect(page.getByRole('list', { name: '同步操作记录' }).getByText('已拒绝', { exact: true })).toBeVisible();
  await expect(page.getByText(/stale_generation/)).toBeVisible();
  await page.screenshot({ path: 'test-results/activity-desktop.png', fullPage: true });
  await page.getByLabel('筛选提交结果').selectOption('no_op');
  await expect(page.getByRole('list', { name: '同步操作记录' }).getByText('无变化', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('筛选提交结果')).toHaveValue('no_op');
  await page.getByRole('link', { name: '设置', exact: true }).click();
  await page.getByLabel('深色', { exact: true }).check();
  await page.getByRole('link', { name: '图库', exact: true }).click();
  await expect(page.getByRole('link', { name: '图库', exact: true })).toHaveAttribute('aria-current', 'page');
  await expect(tile).toBeVisible();
  await page.screenshot({ path: 'test-results/library-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('link', { name: '同步状态', exact: true }).click();
  await expect(page.getByRole('link', { name: '同步状态', exact: true })).toHaveAttribute('aria-current', 'page');
  await page.screenshot({ path: 'test-results/sync-mobile-dark.png', fullPage: true });
  await page.getByRole('link', { name: '操作记录', exact: true }).click();
  await expect(page.getByRole('link', { name: '操作记录', exact: true })).toHaveAttribute('aria-current', 'page');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/activity-mobile-dark.png', fullPage: true });
  expect(errors).toEqual([]);
});
