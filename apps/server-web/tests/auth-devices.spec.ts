import { test, expect } from '@playwright/test';

test('login, create and revoke a device, keep session across reload, then logout', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && /Content Security Policy|Refused to/.test(message.text())) errors.push(message.text()); });
  await page.goto('/devices');
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('用户名').fill('admin');
  await page.getByLabel('密码', { exact: true }).fill('memedock-test-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page).toHaveURL(/\/library$/);
  await page.getByRole('link', { name: '设备管理', exact: true }).click();
  const addDevice = page.getByRole('button', { name: '添加设备', exact: true });
  await addDevice.click();
  await expect(page.getByLabel('设备名称')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(addDevice).toBeFocused();
  await addDevice.click();
  await page.getByLabel('设备名称').fill('Browser smoke phone');
  await page.getByRole('button', { name: '创建', exact: true }).click();
  const token = await page.getByLabel('设备 Token').inputValue();
  expect(token).toMatch(/^mdk_/);
  const verified = await request.get('/api/v1/device/verify', { headers: { Authorization: `Bearer ${token}` } });
  expect(verified.status()).toBe(200);
  await page.getByRole('button', { name: '完成', exact: true }).click();
  await page.reload();
  await expect(page.getByText('Browser smoke phone', { exact: true })).toBeVisible();
  await expect(page.getByLabel('设备 Token')).toHaveCount(0);
  await page.screenshot({ path: 'test-results/devices-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/devices-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.getByRole('button', { name: '更多操作：Browser smoke phone' }).click();
  await page.getByRole('menuitem', { name: '撤销授权' }).click();
  await expect(page.getByRole('alertdialog')).toBeVisible();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toHaveCount(0);
  await expect(page.getByText('可连接', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '更多操作：Browser smoke phone' }).click();
  await page.getByRole('menuitem', { name: '撤销授权' }).click();
  await page.getByRole('button', { name: '撤销授权', exact: true }).click();
  await expect(page.getByText(/已撤销/)).toBeVisible();
  const revoked = await request.get('/api/v1/device/verify', { headers: { Authorization: `Bearer ${token}` } });
  expect(revoked.status()).toBe(401);
  await page.getByRole('link', { name: '设置', exact: true }).click();
  await expect(page).toHaveURL(/\/settings$/);
  await page.reload();
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();

  // Test language switching
  await page.getByLabel('English', { exact: true }).check();
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('English', { exact: true })).toBeChecked();
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible();
  await page.getByLabel('简体中文', { exact: true }).check();
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();

  // Theme settings
  await page.getByLabel('深色', { exact: true }).check();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.getByLabel('深色', { exact: true })).toBeChecked();
  await page.screenshot({ path: 'test-results/settings-dark.png', fullPage: true });
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' });
  await page.getByLabel('跟随系统', { exact: true }).nth(1).check();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByLabel('浅色', { exact: true }).check();
  await expect(page.locator('body')).toHaveCSS('color', 'rgb(22, 24, 28)');
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toHaveCSS('color', 'rgb(22, 24, 28)');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/settings-mobile.png', fullPage: true });
  await page.getByLabel('当前密码').fill('memedock-test-password');
  await page.getByLabel('新密码', { exact: true }).fill('memedock-updated-password');
  await page.getByLabel('确认新密码').fill('memedock-updated-password');
  await page.getByRole('button', { name: '保存并重新登录' }).click();
  await expect(page).toHaveURL(/\/login\?passwordChanged=1$/);
  await page.getByLabel('用户名').fill('admin');
  await page.getByLabel('密码', { exact: true }).fill('memedock-updated-password');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page).toHaveURL(/\/library$/);
  await page.getByRole('button', { name: '账户菜单' }).click();
  await page.getByRole('menuitem', { name: '退出登录' }).click();
  await expect(page).toHaveURL(/\/login$/);
  expect(errors).toEqual([]);
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.screenshot({ path: 'test-results/login-desktop.png', fullPage: true });
});
